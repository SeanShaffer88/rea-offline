#!/usr/bin/env python3
"""Regenerate src/imphash_ordinals.rs from pefile's *frozen* imphash tables.

Why this exists
---------------
`imphash` is only useful if it produces the same digest as everyone else.
pefile resolves ordinal imports against ordinal->name tables, and those
tables have been corrected over the years — which silently changed imphash
values. Upstream therefore keeps a second, *frozen* copy used only by
`get_imphash()`, documented as:

    "Imphash-specific ordinal tables must remain frozen to the state when the
     original implementation was written so that imphash values remain
     compatible with YARA, YARA-X, and other tools based on the original
     pefile implementation."

This script reads those frozen tables and emits them as Rust data. It performs
no network access: point it at a checkout (or unpacked wheel) of pefile.

Usage
-----
    python3 scripts/regen-imphash-ordinals.py /path/to/pefile/ordlookup

The generated file is checked in, so building this crate never needs Python,
pefile, or a network. Re-run only to re-verify or to pick up an upstream
correction, and re-check the test vectors in src/rea_bridge.rs afterwards.

pefile is MIT licensed; the generated table is a derived work and carries the
attribution in its header.
"""

import argparse
import ast
import pathlib
import sys

HEADER = """//! Frozen ordinal->name tables for imphash compatibility.
//!
//! GENERATED by `scripts/regen-imphash-ordinals.py` — do not edit by hand.
//! Source: erocarrera/pefile, `ordlookup/imphash_ws2_32.py` and
//! `ordlookup/imphash_oleaut32.py` (MIT licensed, (c) pefile contributors).
//!
//! These are the *imphash-specific* tables, deliberately frozen upstream to
//! the state of the original implementation so digests stay comparable with
//! VirusTotal, YARA and YARA-X. pefile's general-purpose ordinal tables have
//! been corrected since and must NOT be used here: they disagree on well over
//! a hundred ws2_32 ordinals alone.
//!
//! Upstream maps `wsock32.dll` onto the ws2_32 table; that quirk is part of
//! the original behaviour and is reproduced here.

/// `(ordinal, name)` sorted by ordinal, for binary search.
pub type OrdinalTable = &'static [(u16, &'static str)];

/// Look up an ordinal the way pefile's imphash does: the frozen table when
/// the DLL has one, otherwise `ord<N>`. `dll` must already be lowercased and
/// must be the full name including extension, as pefile keys it.
pub fn lookup(dll: &str, ordinal: u16) -> String {
    let table: Option<OrdinalTable> = match dll {
        "ws2_32.dll" | "wsock32.dll" => Some(WS2_32),
        "oleaut32.dll" => Some(OLEAUT32),
        _ => None,
    };
    if let Some(table) = table {
        if let Ok(index) = table.binary_search_by_key(&ordinal, |(ord, _)| *ord) {
            return table[index].1.to_ascii_lowercase();
        }
    }
    format!("ord{ordinal}")
}
"""


def read_ord_names(path: pathlib.Path) -> dict:
    """Extract the `ord_names` dict literal without importing the module."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "ord_names" for t in node.targets
        ):
            literal = ast.literal_eval(node.value)
            out = {}
            for key, value in literal.items():
                key = key.decode() if isinstance(key, bytes) else key
                value = value.decode() if isinstance(value, bytes) else value
                if not value.isascii():
                    raise SystemExit(f"non-ASCII symbol name in {path}: {value!r}")
                out[int(key)] = value
            return out
    raise SystemExit(f"no ord_names dict found in {path}")


def emit(name: str, table: dict) -> str:
    lines = [f"pub const {name}: OrdinalTable = &["]
    for ordinal in sorted(table):
        symbol = table[ordinal].replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    ({ordinal}, "{symbol}"),')
    lines.append("];")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ordlookup", type=pathlib.Path, help="path to pefile's ordlookup directory")
    parser.add_argument(
        "--out",
        type=pathlib.Path,
        default=pathlib.Path(__file__).resolve().parent.parent / "src" / "imphash_ordinals.rs",
    )
    args = parser.parse_args()

    ws2 = read_ord_names(args.ordlookup / "imphash_ws2_32.py")
    ole = read_ord_names(args.ordlookup / "imphash_oleaut32.py")
    for label, table in [("ws2_32", ws2), ("oleaut32", ole)]:
        if not table or max(table) > 0xFFFF:
            raise SystemExit(f"{label}: table empty or ordinal out of u16 range")

    text = "\n\n".join([HEADER, emit("WS2_32", ws2), emit("OLEAUT32", ole)]) + "\n"
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out}: ws2_32={len(ws2)} entries, oleaut32={len(ole)} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
